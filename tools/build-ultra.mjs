// Builds /ultra.js in the repo root: one file Lampa installs as a normal plugin,
// a plain concatenation of everything listed in plugin/ultra.json; URL entries are loaded at runtime.
// Usage: node tools/build-ultra.mjs
import fs from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (p) => fs.readFileSync(new URL(p, root), 'utf8');

// Entries are "file.js" / "https://…" or { src, about }; about is a note for people only.
const list = JSON.parse(read('plugin/ultra.json')).plugins.map((e) => (typeof e === 'string' ? e : e.src));
const parts = list.map((name) => {
  if (!name) throw new Error('plugin entry without src');
  if (/^https?:\/\//.test(name)) {
    return `\n;/* ---- ${name} ---- */\nLampa.Utils.putScriptAsync([${JSON.stringify(name)}], function () {});\n`;
  }
  const code = read('plugin/' + name).replace(/\s+$/, '');
  if (!code) throw new Error('empty plugin: ' + name);
  // The leading ; keeps a plugin starting with ( or [ from being read as a call on the one before.
  return `\n;/* ---- ${name} ---- */\n${code}\n`;
});

const head = [
  '// Lampa bundle: ' + list.join(', '),
  '// Generated by tools/build-ultra.mjs from plugin/*.js — edit those, not this file.',
  '// Install: ' + 'https://edembey.github.io/lampa-torbox/ultra.js',
].join('\n');

fs.writeFileSync(new URL('ultra.js', root), head + parts.join(''));
console.log('ultra.js:', list.length, 'plugins,', fs.statSync(new URL('ultra.js', root)).size, 'bytes');
